import type { Language } from "../types/analysis.js";
import { generatedFilePatternsFor, vendoredBannersFor } from "../extractors/registry.js";

/**
 * Detects generated source from its file name — or from the marker its
 * generator writes at the top (`isGeneratedSource`).
 *
 * The existing generated-code detection is directory-based — barrel trees
 * discovered by `dead-code`, a `generated/` or `vendor/` path segment, plus
 * whatever a team writes into `.clarifydoc/config.json`. Every ecosystem also
 * has codegen that names FILES rather than folders, and all of it was
 * invisible: `Form1.Designer.cs` sits beside `Form1.cs`, `user.pb.go` beside
 * `user.go`. Its size, repetition and complexity counted against the team.
 *
 * A match does not stop the file being analyzed. Its screens, routes and
 * entities are real facts — a WinForms designer file is the only place a form's
 * layout exists — it is excluded from the quality signals.
 *
 * Two layers, mirroring the test-file detector: one cross-language convention
 * here, and the language-idiomatic patterns declared by each plugin.
 */

/** The one convention every ecosystem shares. Directory tokens are `dead-code`'s job. */
const GENERIC_GENERATED_PATTERNS: readonly RegExp[] = [/\.generated\.[^.\\/]+$/i];

const combinedCache = new Map<Language | "<none>", readonly RegExp[]>();

/** The generic generated-file patterns plus the language's own, merged once per language and cached. */
function patternsFor(language?: Language): readonly RegExp[] {
  const key = language ?? "<none>";
  let combined = combinedCache.get(key);
  if (!combined) {
    combined = language
      ? [...GENERIC_GENERATED_PATTERNS, ...generatedFilePatternsFor(language)]
      : GENERIC_GENERATED_PATTERNS;
    combinedCache.set(key, combined);
  }
  return combined;
}

/**
 * True when the file name follows a generated-code convention. Pass `language`
 * to apply that language's plugin-declared patterns too.
 */
export function isGeneratedFile(filePath: string, language?: Language): boolean {
  for (const re of patternsFor(language)) {
    if (re.test(filePath)) return true;
  }
  return false;
}

/**
 * Markers a generator writes at the top of its output, each a published
 * convention rather than a guess: Go's `^// Code generated … DO NOT EDIT.$`
 * (gqlgen, sqlc, mockgen, wire, protoc-gen-go), .NET's `<auto-generated>`
 * (NSwag, EF migrations' designers, T4), `@generated` (Relay, Buck, Thrift,
 * prisma-client, tree-sitter's `parser.c`), a Java `@Generated` class (OpenAPI
 * Generator, MapStruct), and the banners parser and lexer generators sign their
 * output with in every language they emit: GNU Bison, flex, ANTLR 3 and 4.
 */
const GENERATED_HEADER_RES: readonly RegExp[] = [
  /\bCode generated\b[^\n]*\bDO NOT EDIT\b/,
  /<auto-generated\b/i,
  /(?:^|[\s*#/])@generated\b/m,
  /^\s*@(?:javax\.annotation\.(?:processing\.)?|jakarta\.annotation\.)?Generated\b/m,
  // JAX-WS / JAXB tools (`wsimport`, `xjc`) sign their output in a Javadoc line.
  /\bThis (?:class|file) was generated by the (?:JAX-WS RI|XML-WS Tools|JavaTM Architecture for XML Binding)/,
  /\bA Bison parser, made by GNU Bison\b/,
  /\b(?:A lexical scanner )?generated by flex\b/,
  /\bGenerated from \S+\.g4? by ANTLR\b/,
  /\$ANTLR \d+\.\d+/,
];

/**
 * Boilerplate only a generator writes, though the file never says "generated": JAXB's
 * `xjc` documents each class with its schema fragment and its `ObjectFactory` the same way.
 */
const GENERATOR_BOILERPLATE_RE =
  /The following schema fragment specifies the expected content contained within this class|This object contains factory methods for each\s*(?:\*\s*)?Java content interface and Java element interface/;
/** A tree-sitter `parser.c` from before the generator signed it: the runtime header, then the table sizes it defines. */
const TREE_SITTER_PARSER_RE = /^#include\s+["<]tree_sitter\/parser\.h[">][\s\S]*?^#define\s+LANGUAGE_VERSION\s+\d+\s*\n#define\s+STATE_COUNT\s+\d+/m;
/** A head line that both says the file is generated and asks not to edit it. */
const GENERATED_NOTICE_RE = /\b(?:auto-?generated|automatically generated|generated (?:by|from|with))\b[^\n]*?\b(?:do not (?:edit|modify)|don'?t (?:edit|modify))\b/i;

/**
 * True when the source opens with a generated-code marker (first 4 KiB: a
 * Java `@Generated` sits after the imports). Authored code does not carry
 * one, so a hit is the generator's own statement.
 *
 * @param sourceText - The whole file
 */
export function isGeneratedSource(sourceText: string): boolean {
  const head = sourceText.slice(0, 4096);
  if (GENERATOR_BOILERPLATE_RE.test(head) || TREE_SITTER_PARSER_RE.test(head)) return true;
  if (!/generated|Bison|\$ANTLR/i.test(head)) return false;
  return GENERATED_HEADER_RES.some((re) => re.test(head)) || GENERATED_NOTICE_RE.test(head);
}

/**
 * The single-file library the source is, by the banner its release writes at
 * the top (first 4 KiB) — the language's `vendoredBanners`: the SQLite
 * amalgamation, nlohmann's `json.hpp`, `stb_*.h`. Undefined for anything
 * else; a path alone never decides it.
 *
 * @param sourceText - The whole file
 * @param language - The file's language
 */
export function vendoredLibraryOf(sourceText: string, language: Language): string | undefined {
  const banners = vendoredBannersFor(language);
  if (banners.length === 0) return undefined;
  const head = sourceText.slice(0, 4096);
  return banners.find((b) => b.banner.test(head))?.library;
}
