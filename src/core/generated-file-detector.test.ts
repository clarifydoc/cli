import { describe, it, expect } from "vitest";
import { isGeneratedFile, isGeneratedSource, vendoredLibraryOf } from "./generated-file-detector.js";

/**
 * Generated-code detection was directory-based, so codegen that names FILES
 * rather than folders was invisible: `Form1.Designer.cs` sits beside
 * `Form1.cs`, `player.pb.go` beside `player.go`. Its size, repetition and
 * complexity counted against the team that neither wrote nor maintains it.
 */
describe("isGeneratedFile", () => {
  const cases: Array<[path: string, language: string | undefined, expected: boolean]> = [
    // C#: designers and source generators — but not a hand-written *Designer class.
    ["src/Forms/FrmMain.Designer.cs", "csharp", true],
    ["src/Forms/Resources.g.cs", "csharp", true],
    ["src/Reports/ReportDesigner.cs", "csharp", false],
    ["src/Forms/FrmMain.cs", "csharp", false],
    // Go: protoc output, not an ordinary file that merely mentions pb.
    ["api/player.pb.go", "go", true],
    ["api/player.pb.gw.go", "go", true],
    ["api/pbutil.go", "go", false],
    // Python
    ["proto/models_pb2.py", "python", true],
    ["proto/models_pb2_grpc.py", "python", true],
    ["proto/pb2_helpers.py", "python", false],
    // Dart build_runner
    ["lib/models/player.g.dart", "dart", true],
    ["lib/models/player.freezed.dart", "dart", true],
    ["lib/models/player.dart", "dart", false],
    // VB designers
    ["Forms/Main.Designer.vb", "vb", true],
    // The one cross-language convention applies without a language.
    ["src/api/client.generated.ts", undefined, true],
    ["src/api/client.generated.ts", "typescript", true],
    ["src/api/client.ts", "typescript", false],
  ];

  for (const [path, language, expected] of cases) {
    it(`${expected ? "flags" : "leaves"} ${path}`, () => {
      expect(isGeneratedFile(path, language as never)).toBe(expected);
    });
  }

  it("does not apply another language's convention", () => {
    // `.g.cs` is C#; a Dart file named that way is not the same thing.
    expect(isGeneratedFile("lib/ball.g.cs", "dart")).toBe(false);
  });
});

describe("isGeneratedSource — the generator's own header", () => {
  it("recognises the published markers", () => {
    expect(isGeneratedSource("// Code generated by github.com/99designs/gqlgen, DO NOT EDIT.\n\npackage graph\n")).toBe(true);
    expect(isGeneratedSource("// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.25.0\n")).toBe(true);
    expect(isGeneratedSource("//------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n")).toBe(true);
    expect(isGeneratedSource("/**\n * @generated SignedSource<<abc>>\n */\n")).toBe(true);
    expect(isGeneratedSource("package a;\nimport javax.annotation.Generated;\n\n@javax.annotation.Generated(\"openapi\")\npublic class Vehicle {}\n")).toBe(true);
    expect(isGeneratedSource("# This file is automatically generated by Alembic - do not edit\n")).toBe(true);
    // JAX-WS wsimport and JAXB xjc output (real-repo FP: a bundled SOAP client analyzed as authored).
    expect(isGeneratedSource("/**\n * This class was generated by the XML-WS Tools.\n * Generated source version: 3.0\n */\npublic class LeagueService {}\n")).toBe(true);
    expect(isGeneratedSource("/**\n * <p>Java class for ClubTYPE complex type</p>.\n * \n * <p>The following schema fragment specifies the expected content contained within this class.</p>\n */\npublic class ClubTYPE {}\n")).toBe(true);
  });

  it("recognises parser and lexer generators' banners in any language they emit", () => {
    expect(isGeneratedSource("/* A Bison parser, made by GNU Bison 3.8.2.  */\n\n/* Bison implementation for Yacc-like parsers in C */\n")).toBe(true);
    expect(isGeneratedSource("// A Bison parser, made by GNU Bison 3.8.2.\n\n// Skeleton interface for Bison LALR(1) parsers in C++\n")).toBe(true);
    expect(isGeneratedSource("#line 2 \"lexer.c\"\n\n#define  YY_INT_ALIGNED short int\n\n/* A lexical scanner generated by flex */\n")).toBe(true);
    expect(isGeneratedSource("// Generated from LeagueParser.g4 by ANTLR 4.13.1\n\nimport * as antlr from \"antlr4ng\";\n")).toBe(true);
    expect(isGeneratedSource("# Generated from Garage.g4 by ANTLR 4.9.3\nfrom antlr4 import *\n")).toBe(true);
    expect(isGeneratedSource("// $ANTLR 3.5.2 Club.g 2024-01-01 10:00:00\npackage league;\n")).toBe(true);
    expect(isGeneratedSource("/* Automatically @generated by tree-sitter v0.25.3 */\n\n#include \"tree_sitter/parser.h\"\n")).toBe(true);
    // Before tree-sitter signed its output: the runtime header and the table sizes only the generator defines.
    expect(isGeneratedSource("#include \"tree_sitter/parser.h\"\n\n#if defined(__GNUC__)\n#pragma GCC diagnostic ignored \"-Wmissing-field-initializers\"\n#endif\n\n#define LANGUAGE_VERSION 14\n#define STATE_COUNT 2517\n#define LARGE_STATE_COUNT 907\n")).toBe(true);
    // A scanner that includes the runtime header is authored.
    expect(isGeneratedSource("#include \"tree_sitter/parser.h\"\n\nenum TokenType { CLUB_NAME };\n\nvoid *tree_sitter_league_external_scanner_create() { return 0; }\n")).toBe(false);
  });

  it("leaves authored code alone", () => {
    expect(isGeneratedSource("// generated ids are unique per tenant\nexport function id() {}\n")).toBe(false);
    expect(isGeneratedSource("def generate():\n    \"\"\"Return a generated token.\"\"\"\n")).toBe(false);
    // The marker must be in the head, not deep in a file that mentions it.
    expect(isGeneratedSource("x".repeat(5000) + "\n// Code generated by x. DO NOT EDIT.\n")).toBe(false);
    // A grammar that says what it is fed to is authored.
    expect(isGeneratedSource("/* The league grammar, compiled with GNU Bison. */\n%token CLUB\n")).toBe(false);
  });
});

describe("vendoredLibraryOf — a single-file library copied into the tree", () => {
  it("names the library by its banner, wherever the file sits", () => {
    expect(vendoredLibraryOf("/****\n** This file is an amalgamation of many separate C source files from SQLite\n** version 3.51.3.\n*/\n", "c")).toBe("SQLite");
    expect(vendoredLibraryOf("//     __ _____ _____ _____\n//  __|  |   __|     |   | |  JSON for Modern C++\n// |  |  |__   |  |  | | | |  version 3.11.3\n", "cpp")).toBe("nlohmann/json");
    expect(vendoredLibraryOf("/* stb_image - v2.28 - public domain image loader - http://nothings.org/stb\n", "cpp")).toBe("stb");
    expect(vendoredLibraryOf("/* miniz.c 3.0.2 - public domain deflate/inflate, zlib-subset, ZIP reading/writing/appending, PNG writing\n", "c")).toBe("miniz");
  });

  it("leaves authored code and other languages alone", () => {
    expect(vendoredLibraryOf("/* Garage storage on top of SQLite. */\n#include \"sqlite3.h\"\n", "c")).toBeUndefined();
    expect(vendoredLibraryOf("// Reads JSON for the league table.\n", "cpp")).toBeUndefined();
    expect(vendoredLibraryOf("/* stb_image - v2.28 - public domain image loader */\n", "python")).toBeUndefined();
  });
});
