import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { execFileSync } from "child_process";
import { mkdtempSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { commitReasons, findReasonComments, reasonParagraph, statesReason } from "./stated-reasons.js";
import { C_STYLE_DOCS, PYTHON_DOCS } from "../extractors/shared/doc-comment-specs.js";

describe("statesReason", () => {
  it("reads causal connectives", () => {
    for (const text of [
      "Sorted by kickoff because the fixture list is read top to bottom",
      "Since the referee can change the score after the whistle, re-read it",
      "since we already hold the lock here",
      "Padded so that the shirt numbers line up",
      "Retry once, otherwise a dropped connection would lose the result",
      "In order to keep the table stable, ties sort by name",
      "Copy the squad to avoid mutating the caller's list",
      "Workaround for the timing chip resetting at midnight",
      "We cannot rely on the clock here, so the server time is used",
      "Required by the league's export format",
      "Needed for the garage view, which joins cars once",
      "Kept for backwards compatibility with old fixture files",
      "The lap time is rounded due to the timer's precision",
    ]) expect(statesReason(text), text).toBe(true);
  });

  it("leaves a since that is a time, an otherwise that is a branch, and plain prose alone", () => {
    for (const text of [
      "Deprecated since v2.3",
      "Available since 2019",
      "since then the club has moved",
      "Seconds since the last pit stop",
      "Otherwise return the default squad",
      "Returns the league table for a season",
      "The player has to be a string or None",
      "TODO: sort the cars",
      "A car has been serviced since the garage was opened",
      "Every club except those required by a league that is being added",
      "event.reason contains the reason for the rejection",
    ]) expect(statesReason(text), text).toBe(false);
  });
});

describe("findReasonComments", () => {
  const ts = [
    "// Copyright 2026 The League Authors. Licensed under the MIT licence because we can.", // 1
    "import { db } from './db';", // 2
    "", // 3
    "// Newest first so that the transfer list", // 4
    "// shows fresh signings on top.", // 5
    "export function listTransfers() {", // 6
    "  // Read twice because the first read can miss a late substitution.", // 7
    "  const a = db.read();", // 8
    "  // const b = db.read(); // because", // 9
    "  // if (b) { return b; }", // 10
    "  return a;", // 11
    "}", // 12
    "", // 13
    "/*", // 14
    " * The garage keeps one car per bay.", // 15
    " */", // 16
    "export function parkCar() {", // 17
    "  const msg = '// because this is a string';", // 18
    "}", // 19
  ].join("\n");
  const spans = [
    { name: "listTransfers", line: 6, endLine: 12 },
    { name: "parkCar", line: 17, endLine: 19 },
  ];

  it("takes the whole comment block, anchored to the function it sits above or in", () => {
    const rows = findReasonComments(ts, "src/transfers.ts", C_STYLE_DOCS, spans);
    expect(rows.map((r) => [r.line, r.endLine, r.anchor?.name, r.anchor?.where, r.text])).toEqual([
      [4, 5, "listTransfers", "above", "Newest first so that the transfer list shows fresh signings on top."],
      [7, 7, "listTransfers", "inside", "Read twice because the first read can miss a late substitution."],
    ]);
  });

  it("reads the language's own comment syntax", () => {
    const py = ["# Cache the table because standings change once a match ends", "def table():", "    return 1"].join("\n");
    expect(findReasonComments(py, "league.py", PYTHON_DOCS, [{ name: "table", line: 2, endLine: 3 }]).map((r) => r.anchor?.name)).toEqual(["table"]);
    // `#` is not a comment in a C-family file.
    expect(findReasonComments("# because\n", "x.ts", C_STYLE_DOCS, [])).toEqual([]);
  });

  it("anchors a comment above a decorator whose arguments spread over rows to the decorated function", () => {
    const src = [
      "// Cached per match day because the standings query is slow.", // 1
      "@ApiResponse({", // 2
      "  status: 200,", // 3
      "  description: 'The table',", // 4
      "})", // 5
      "@Get('table')", // 6
      "table() {}", // 7
    ].join("\n");
    const rows = findReasonComments(src, "src/league.controller.ts", C_STYLE_DOCS, [{ name: "table", line: 7, endLine: 7 }]);
    expect(rows.map((r) => [r.anchor?.name, r.anchor?.where])).toEqual([["table", "above"]]);
  });

  it("reads nothing in a generated file", () => {
    const gen = ["// Code generated by a tool. DO NOT EDIT.", "// Kept because the schema says so.", "export const x = 1;"].join("\n");
    expect(findReasonComments(gen, "gen.ts", C_STYLE_DOCS, [])).toEqual([]);
  });
});

describe("reasonParagraph", () => {
  it("picks the paragraph that states a reason, trailers and quotes left out", () => {
    const body = [
      "Moves the standings query into the league service.",
      "",
      "The table is cached per match day because recomputing it on every",
      "request made the fixture page slow.",
      "",
      "> because a quoted release note is not ours",
      "",
      "Signed-off-by: Coach <coach@example.com>",
    ].join("\n");
    expect(reasonParagraph(body)).toBe("The table is cached per match day because recomputing it on every request made the fixture page slow.");
    expect(reasonParagraph("Just tidies the garage module.\n\nSigned-off-by: Coach <c@e>")).toBeNull();
  });
});

describe("commitReasons", () => {
  let root = "";
  const git = (args: string[], date = "2026-01-01T10:00:00Z") =>
    execFileSync("git", ["-c", "user.name=Coach", "-c", "user.email=coach@example.com", "-C", root, ...args], {
      env: { ...process.env, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date },
      stdio: "pipe",
    });

  beforeAll(() => {
    root = mkdtempSync(join(tmpdir(), "clarifydoc-stated-reasons-"));
    git(["init", "-q"]);
    writeFileSync(join(root, "league.ts"), ["export function table() {", "  return 1;", "}", "", "export function fixtures() {", "  return 2;", "}", ""].join("\n"));
    git(["add", "-A"]);
    git(["commit", "-q", "-m", "League table"]);
    writeFileSync(join(root, "league.ts"), ["export function table() {", "  return 10;", "}", "", "export function fixtures() {", "  return 2;", "}", ""].join("\n"));
    git(["commit", "-q", "-am", "Scale the table (#42)", "-m", "Points are stored times ten so that half points survive integer columns."], "2026-02-01T10:00:00Z");
    writeFileSync(join(root, "league.ts"), ["export function table() {", "  return 10;", "}", "", "export function fixtures() {", "  return 3;", "}", ""].join("\n"));
    git(["commit", "-q", "-am", "Merge pull request #7 from coach/fixtures", "-m", "One more fixture because the cup final was added."], "2026-03-01T10:00:00Z");
    git(["mv", "league.ts", "season.ts"]);
    git(["commit", "-q", "-m", "Rename league to season", "-m", "Just a rename."], "2026-04-01T10:00:00Z");
  });
  afterAll(() => rmSync(root, { recursive: true, force: true }));

  it("reads the reason from each commit body of the file, across renames, with the pull request", async () => {
    const r = await commitReasons(root, "season.ts");
    expect(r.status).toBe("ok");
    expect(r.scope).toBe("file");
    expect(r.scanned).toBe(4);
    expect(r.reasons.map((c) => [c.date, c.subject, c.pr, c.excerpt])).toEqual([
      ["2026-03-01", "Merge pull request #7 from coach/fixtures", 7, "One more fixture because the cup final was added."],
      ["2026-02-01", "Scale the table (#42)", 42, "Points are stored times ten so that half points survive integer columns."],
    ]);
    expect(r.reasons[0]!.sha).toMatch(/^[0-9a-f]{7,}$/);
  });

  it("narrows to the commits that touched a line range", async () => {
    const r = await commitReasons(root, "season.ts", { lines: [1, 3] });
    expect(r.scope).toBe("lines");
    expect(r.reasons.map((c) => c.pr)).toEqual([42]);
  });

  it("says when there is no git", async () => {
    const plain = mkdtempSync(join(tmpdir(), "clarifydoc-no-git-"));
    try {
      expect((await commitReasons(plain, "a.ts")).status).toBe("no-git");
    } finally {
      rmSync(plain, { recursive: true, force: true });
    }
  });
});
