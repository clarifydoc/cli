/**
 * Plain HTML page extraction (regex path) — for vanilla multi-page static sites
 * (no framework, no build step: hand-written `.html` pages wired together with
 * `<a href>` links and `<script src>` includes).
 *
 * The engine's screen→API→DB model has a *screen* tier, and for a static MPA the
 * HTML pages ARE the screens. So this spec turns each page into a routed screen
 * and surfaces the wiring around it:
 *
 *  - the page itself          → ONE `frontend` route at the page's URL (its file
 *                               path); `componentPath: null` so the screen builder
 *                               treats the page as an inline screen (like Blazor
 *                               `@page`). `<a href="other.html">` links become the
 *                               screen's `navigatesTo` edges (built in core).
 *  - `<script src="./x.js">`  → imports (LOCAL only) → component-graph edges from
 *                               the page to its JS modules, so the page connects
 *                               to the JS call graph (and its `fetch` api-calls).
 *  - forms / buttons / inputs / inline `on*=` handlers → interactive elements.
 *
 * There are no functions/classes in HTML markup (the behaviour lives in the
 * `<script src>` JS files, parsed by the JS plugin), so those patterns are empty.
 */

// ─── Generated API-doc detection ────────────────────────────────────────────

/**
 * API-documentation generators whose HTML output is a BUILD ARTIFACT of the
 * code, not part of the application's UI. A committed `docs/` tree from one of
 * these (one page per class/member) otherwise floods the report with thousands
 * of phantom screens and frontend routes — a Delphi samples repo shipped 3,925
 * DocInsight pages next to 183 real source files.
 *
 * Deliberately NOT matched: site generators (Hugo, Jekyll, Gatsby, WordPress…)
 * — their output IS the site's UI and stays analyzed.
 */
const API_DOC_GENERATORS =
  /^\s*(docinsight|pasdoc|doxygen|rustdoc|typedoc|jsdoc|docfx|sphinx|haddock|yard|rdoc|pdoc|epydoc|naturaldocs|natural docs|sandcastle|compodoc|dokka|scaladoc|swagger-ui)\b/i;

/** Head window: generator metas sit in <head>; avoids scanning megabyte bodies. */
const HEAD_WINDOW = 4096;

/** Name of the API-doc generator that produced this page, or null. */
export function apiDocGeneratorOf(source: string): string | null {
  const head = source.slice(0, HEAD_WINDOW);
  // <meta name="generator" content="X"> — attribute order varies by tool.
  for (const tag of head.matchAll(/<meta\b[^>]*>/gi)) {
    if (!/\bname\s*=\s*["']generator["']/i.test(tag[0])) continue;
    const content = tag[0].match(/\bcontent\s*=\s*["']([^"']*)["']/i)?.[1];
    if (content && API_DOC_GENERATORS.test(content)) return content;
  }
  // JavaDoc stamps a comment, not a meta tag.
  if (/<!--\s*Generated by javadoc\b/i.test(head)) return "javadoc";
  return null;
}

/**
 * A directory guard: the stub `index.html` a framework drops into every
 * folder so a misconfigured server lists nothing (CodeIgniter's "403
 * Forbidden — Directory access is forbidden."). It is no page of the app.
 */
function isDirectoryGuard(source: string): boolean {
  return source.length < 1024 && /<title>\s*403 Forbidden\s*<\/title>/i.test(source) && !/<(?:a|form|script|button|input)\b/i.test(source);
}

/** Content-sniffing preprocess: skip pages that are generated API reference, and directory guards. */
export function htmlPreprocess(rawSource: string): { skip: string } | null {
  const generator = apiDocGeneratorOf(rawSource);
  if (generator) return { skip: `generated API documentation (${generator})` };
  return isDirectoryGuard(rawSource) ? { skip: "directory guard page (403 Forbidden)" } : null;
}

// ─── Route (the page itself) ────────────────────────────────────────────────

/**
 * The page's route path = its project-relative URL. `index.html` represents its
 * directory (`foo/index.html` → `/foo/`, top-level → `/`); every other page maps
 * to `/<path>`. Backslashes are normalised to URL slashes.
 */
export function pageRoutePath(filePath: string): string {
  const rel = filePath.replace(/\\/g, "/").replace(/^\.\//, "");
  const asDir = rel.replace(/(^|\/)index\.html?$/i, "$1");
  const path = asDir === "" ? "/" : asDir;
  return path.startsWith("/") ? path : "/" + path;
}

/** The page's `<title>` text, or null. */
function pageTitle(lines: string[]): string | null {
  const m = lines.join("\n").match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  const title = m ? m[1].trim().replace(/\s+/g, " ") : "";
  // A template's placeholder (`{{TITLE}}`, `<%= title %>`, `%PAGE_TITLE%`) is filled at build or serve time: no title.
  return title && !TITLE_PLACEHOLDER_RE.test(title) ? title : null;
}

/** A `<title>` that is only a template placeholder. */
export const TITLE_PLACEHOLDER_RE = /^(?:\{\{[^{}]*\}\}|\{%[^%]*%\}|<%=?[^%]*%>|%[A-Za-z_][\w.]*%|\$\{[^}]*\}|\[\[[^\]]*\]\]|__[A-Z][A-Z0-9_]*__)$/;

/** A framework's document shell (SvelteKit `src/app.html`, `%sveltekit.body%`; Vite/CRA-style `%PUBLIC_URL%` aside): it wraps every page and is none. */
const DOCUMENT_SHELL_RE = /%sveltekit\.(?:body|head)%/;

/** A directory that holds documentation, not the app. */
const DOCS_DIR_RE = /(?:^|\/)(?:docs?|documentation|architecture|diagrams?)\//i;

/**
 * A diagram written as a page (`docs/architecture/flows.html`: an inline `<svg>` or a Mermaid block,
 * perhaps with export buttons) in a documentation directory: it is read, never navigated — no
 * form, no field, no link to another page — so it is no route or screen of the app.
 */
export function isDiagramDocument(lines: readonly string[], filePath: string): boolean {
  if (!DOCS_DIR_RE.test(filePath)) return false;
  const text = lines.join("\n");
  if (!/<svg\b|class\s*=\s*["'][^"']*\bmermaid\b/i.test(text)) return false;
  if (/<(?:form|input|select|textarea)\b/i.test(text)) return false;
  // A link to another page of the site (not an anchor, not an external URL).
  return !/<a\b[^>]*\bhref\s*=\s*["'](?![#"']|[a-z][\w+.-]*:|\/\/)/i.test(text);
}

function extractHtmlRoutes(lines: string[], filePath?: string): RouteInfo[] {
  if (!filePath || lines.some((l) => DOCUMENT_SHELL_RE.test(l))) return [];
  if (isDiagramDocument(lines, filePath)) return [];
  return [
    {
      path: pageRoutePath(filePath),
      httpMethod: null,
      kind: "frontend",
      // The page IS the screen — no separate component file, so the screen
      // builder treats this as an inline route on the .html itself.
      componentPath: null,
      // The <title> is a friendly handle for the route; the screen caption is
      // derived from it in core too.
      handler: pageTitle(lines),
      calls: [],
      middleware: [],
      line: 1,
    },
  ];
}

// ─── Markup isolation (blank comments + inline <script>/<style> bodies) ──────

/**
 * Return a copy of `lines` with HTML comment spans and inline `<script>`/`<style>`
 * BODIES blanked, so the element scan only ever sees real page markup (a `if(x<y)`
 * in an inline script must never read as a `<y>` tag, and commented-out markup
 * must not count). Line numbers are preserved 1:1. The opening `<script …>`/`<style …>`
 * tag itself is kept (import extraction reads `src` from the raw lines separately).
 */
export function maskMarkup(lines: string[]): string[] {
  const out: string[] = [];
  let inComment = false;
  let blockTag: string | null = null; // inside a <script>/<style> body
  for (const raw of lines) {
    let line = raw;

    if (blockTag) {
      const end = line.toLowerCase().indexOf("</" + blockTag);
      if (end < 0) { out.push(""); continue; }
      line = " ".repeat(end) + line.slice(end);
      blockTag = null;
    }

    // Comments (may span lines).
    if (inComment) {
      const end = line.indexOf("-->");
      if (end < 0) { out.push(""); continue; }
      line = line.slice(end + 3);
      inComment = false;
    }
    for (let open = line.indexOf("<!--"); open >= 0; open = line.indexOf("<!--")) {
      const end = line.indexOf("-->", open + 4);
      if (end < 0) { line = line.slice(0, open); inComment = true; break; }
      line = line.slice(0, open) + line.slice(end + 3);
    }

    // Inline <script>/<style> bodies (keep the opening tag, drop the body).
    const sb = line.match(/<(script|style)\b[^>]*>/i);
    if (sb && sb.index !== undefined) {
      const tag = sb[1].toLowerCase();
      const bodyStart = sb.index + sb[0].length;
      const closeIdx = line.toLowerCase().indexOf("</" + tag, bodyStart);
      if (closeIdx < 0) {
        line = line.slice(0, bodyStart);
        blockTag = tag;
      } else {
        line = line.slice(0, bodyStart) + line.slice(closeIdx);
      }
    }

    out.push(line);
  }
  return out;
}

// ─── Interactive elements (forms, buttons, inputs, inline handlers) ─────────

const FORM_CONTROL: Record<string, InteractiveElementInfo["element"]> = {
  form: "form",
  button: "button",
  input: "input",
  select: "select",
  textarea: "textarea",
};

/** Native event implied by an interactive control (when it carries no inline handler). */
const NATIVE_EVENT: Record<string, string> = {
  form: "submit",
  button: "click",
  input: "input",
  select: "change",
  textarea: "input",
  a: "click",
};

/** Tag → element kind for a non-control tag that carries an inline handler. */
const ELEMENT_FOR_TAG: Record<string, InteractiveElementInfo["element"]> = {
  a: "link",
  button: "button",
  form: "form",
  input: "input",
  select: "select",
  textarea: "textarea",
};

/** A `<tag ...>` opening plus the attribute text on the SAME line (stops at `>`), or a `</tag` closing. */
const TAG_RE = /<\/?([a-zA-Z][\w-]*)\b([^>]*)/g;
/** Tags whose attributes are read past a line break: where a request is stated. */
const READS_WRAPPED = new Set(["form", "button", "input", "a"]);
/** Inline event handlers: `onclick="foo()"`, `onsubmit='...'`. The `\b` keeps
 *  attributes merely CONTAINING "on" out — without it, `content="notranslate"`
 *  matched as event "ontent" / handler "notranslate". */
const HANDLER_RE = /\bon([a-z]+)\s*=\s*"([^"]*)"|\bon([a-z]+)\s*=\s*'([^']*)'/gi;
/** Alpine.js / petite-vue event directives: `@click="changeRange"`, `x-on:submit.prevent="save()"`.
 *  Only DOM event names: a template dialect's own `@word=` attribute (Razor `@bind=`) is no handler. */
const DIRECTIVE_HANDLER_RE =
  /(?:^|\s)(?:@|x-on:|v-on:)(click|dblclick|submit|change|input|keyup|keydown|keypress|focus|blur|mouseenter|mouseleave|mouseover|mouseout|mousedown|mouseup|scroll|select|reset|paste|drop|dragstart|dragend|touchstart|touchend)(?:\.[\w.-]+)?\s*=\s*(?:"([^"]*)"|'([^']*)')/gi;
/** The first inline handler an element's attributes carry: `onclick="…"` or an event directive. */
function inlineHandler(attrs: string): { event: string; handler: string | null } | null {
  const on = HANDLER_RE.exec(attrs);
  HANDLER_RE.lastIndex = 0;
  if (on) return { event: "on" + (on[1] ?? on[3])!.toLowerCase(), handler: cleanHandler((on[2] ?? on[4])!) };
  const directive = DIRECTIVE_HANDLER_RE.exec(attrs);
  DIRECTIVE_HANDLER_RE.lastIndex = 0;
  return directive ? { event: "on" + directive[1]!.toLowerCase(), handler: cleanHandler((directive[2] ?? directive[3])!) } : null;
}
/** Input types that are state/filter noise rather than meaningful actions. */
const SKIP_INPUT_TYPES = new Set(["checkbox", "radio", "hidden"]);

/** Pull a clean handler name from an inline-handler value: a call wins, then a
 *  bare member path; lambdas/expressions fall back to null. */
function cleanHandler(raw: string): string | null {
  const val = raw.trim();
  const call = val.match(/([A-Za-z_$][\w$]*)\s*\(/);
  if (call) return call[1]!;
  const ident = val.match(/^([A-Za-z_$][\w$.]*)$/);
  if (ident) return ident[1]!;
  return null;
}

// Compiled once per attribute name — the JSP plugin reads a handful of fixed
// attributes on every taglib tag, which made per-call compilation a hot spot.
const ATTR_RE_CACHE = new Map<string, RegExp>();

export function attr(attrs: string, name: string): string | null {
  let re = ATTR_RE_CACHE.get(name);
  if (!re) {
    re = new RegExp(`\\b${name}\\s*=\\s*"([^"]*)"|\\b${name}\\s*=\\s*'([^']*)'`, "i");
    ATTR_RE_CACHE.set(name, re);
  }
  const m = attrs.match(re);
  return m ? (m[1] ?? m[2] ?? null) : null;
}

/** `attr` anchored on whitespace, so `data-action` / `data-href` never read as `action` / `href`. */
function exactAttr(attrs: string, name: string): string | undefined {
  return new RegExp(`(?:^|\\s)${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)')`, "i").exec(attrs)?.slice(1).find((v) => v !== undefined);
}

/** A Thymeleaf link expression's path: `@{/signup}`, `@{/fixtures/{id}(id=${f.id})}` → `/fixtures/{id}`. */
function thymeleafUrl(value: string | undefined): string | undefined {
  const inner = value ? /^\s*@\{([\s\S]*)\}\s*$/.exec(value)?.[1] : undefined;
  const path = inner?.split("(")[0]!.trim();
  return path?.startsWith("/") && !/\s/.test(path) ? path : undefined;
}

/** A link to a page or an asset is navigation (core reads it), not a request to a route. */
const STATIC_FILE = /\.(?:html?|css|js|mjs|map|png|jpe?g|gif|svg|webp|ico|pdf|txt|xml|json|woff2?|ttf|zip)$/i;

type ElementRequest = NonNullable<InteractiveElementInfo["request"]>;

/** What a `<form>` submits: its literal app-path `action`, by its `method` (GET when unset, as browsers do). */
function formRequest(attrs: string, actionAttr = "action", methodAttr = "method", fallbackMethod = "GET"): ElementRequest | undefined {
  const target = literalPath(exactAttr(attrs, actionAttr) ?? thymeleafUrl(exactAttr(attrs, `th:${actionAttr}`)));
  const method = (exactAttr(attrs, methodAttr) ?? fallbackMethod).toUpperCase();
  return target && method !== "DIALOG" ? { method, target } : undefined;
}

/**
 * The text inside the `<tag>` that opens at `markup[line]` column `from`, up to
 * its `</tag>` (a few lines at most): nested tags and `{{ … }}` dropped,
 * whitespace collapsed, capped. Undefined when there is none to read, or the
 * tag does not close nearby (a link wrapping a whole card names nothing).
 */
function innerText(markup: string[], line: number, from: number, tag: string): string | undefined {
  let text = "";
  for (let j = line, col = from; ; j++, col = 0) {
    if (j >= Math.min(markup.length, line + 8)) return undefined;
    const rest = markup[j]!.slice(col);
    const close = rest.toLowerCase().indexOf(`</${tag}`);
    text += " " + (close < 0 ? rest : rest.slice(0, close));
    if (close >= 0) break;
  }
  const open = text.indexOf(">");
  const clean = text.slice(open + 1).replace(/<[^>]*>?|\{\{[\s\S]*?\}\}|&nbsp;/g, " ").replace(/\s+/g, " ").trim();
  return clean ? (clean.length > 60 ? clean.slice(0, 57) + "…" : clean) : undefined;
}

/** The form a submit control sits in. */
interface OpenForm { method: string; request?: ElementRequest }

/**
 * The page's controls, links and inline handlers. Every `<a href>` is a click
 * (a pure `#fragment` or `javascript:` link without a handler is no action);
 * a submit control — `<button>` of type submit (the default inside a form),
 * `<input type="submit|image">` — sends what its enclosing `<form>` sends,
 * unless its own `formaction` / `formmethod` say otherwise.
 *
 * With `requests`, a form `action`, a submit control and a link to a literal
 * app path carry that `request` and are named after it (`post_cart_checkout`),
 * so `materializeElementRequests` can hand them to the route linker; callers
 * that read requests their own way (template dialects, JSP) leave it off.
 */
export function extractHtmlInteractiveElements(lines: string[], opts: { requests?: boolean } = {}): InteractiveElementInfo[] {
  const markup = maskMarkup(lines);
  const out: InteractiveElementInfo[] = [];
  const forms: OpenForm[] = [];
  const withRequest = (el: InteractiveElementInfo, request: ElementRequest | undefined): InteractiveElementInfo =>
    opts.requests && request ? { ...el, handler: handlerOf(request.method, request.target), request } : el;
  for (let i = 0; i < markup.length; i++) {
    const ln = i + 1;
    for (const m of markup[i]!.matchAll(TAG_RE)) {
      const tag = m[1]!.toLowerCase();
      if (m[0][1] === "/") {
        if (tag === "form") forms.pop();
        continue;
      }
      let attrs = m[2] ?? "";
      // A tag whose attributes wrap onto the next lines: read them up to its `>`.
      if (READS_WRAPPED.has(tag) && m.index! + m[0].length >= markup[i]!.length) {
        for (let j = i + 1; j < Math.min(markup.length, i + 12); j++) {
          const close = markup[j]!.indexOf(">");
          attrs += " " + (close < 0 ? markup[j]! : markup[j]!.slice(0, close));
          if (close >= 0) break;
        }
      }
      const inline = inlineHandler(attrs);
      const control = FORM_CONTROL[tag];
      const id = attr(attrs, "id");
      const type = (attr(attrs, "type") ?? (tag === "button" ? "submit" : "text")).toLowerCase();
      const text = tag === "a" || tag === "button" ? innerText(markup, i, m.index!, tag)
        : tag === "input" && (type === "submit" || type === "button" || type === "reset") ? attr(attrs, "value")?.trim() || undefined
        : undefined;
      const caption = text ? { caption: text } : {};
      // What a page script can find a handler-less element by.
      const selector = inline ? undefined : selectorOf(tag, attrs);
      const add = (el: InteractiveElementInfo): void => {
        out.push(selector && !el.request && (el.handler === null || el.handler === id) ? { ...el, selector } : el);
      };

      if (tag === "form") {
        const request = formRequest(attrs);
        forms.push({ method: (exactAttr(attrs, "method") ?? "GET").toUpperCase(), request });
        const el: InteractiveElementInfo = { element: "form", event: inline?.event ?? "submit", handler: inline?.handler ?? id, line: ln };
        add(inline ? el : withRequest(el, request));
        continue;
      }

      // A submit control sends its form: `formaction` / `formmethod` first, then the enclosing form's.
      if ((tag === "button" && type === "submit") || (tag === "input" && (type === "submit" || type === "image"))) {
        const form = forms[forms.length - 1];
        const request = formRequest(attrs, "formaction", "formmethod", form?.method) ?? form?.request;
        const el: InteractiveElementInfo = { element: "button", event: inline?.event ?? "click", handler: inline?.handler ?? id, line: ln, ...caption };
        add(inline ? el : withRequest(el, request));
        continue;
      }

      if (control) {
        if (tag === "input") {
          // Skip checkbox/radio/hidden inputs — filter/state noise, not actions.
          if (SKIP_INPUT_TYPES.has(type)) continue;
          // A button/reset input is really a button.
          if (type === "button" || type === "reset") {
            add({ element: "button", event: inline?.event ?? "click", handler: inline?.handler ?? id, line: ln, ...caption });
            continue;
          }
        }
        add({
          element: control,
          event: inline?.event ?? NATIVE_EVENT[tag] ?? "click",
          handler: inline?.handler ?? id,
          line: ln,
          ...caption,
        });
      } else if (inline) {
        // A non-control element (a/span/div/li…) carrying an inline handler.
        add({
          element: ELEMENT_FOR_TAG[tag] ?? "custom",
          event: inline.event,
          handler: inline.handler,
          line: ln,
          ...caption,
        });
      } else if (tag === "a") {
        // A link is clicked like a button; one to a route of the app is a GET of it.
        const href = exactAttr(attrs, "href")?.trim();
        if (!href || href.startsWith("#") || /^javascript:/i.test(href)) continue;
        const target = literalPath(href);
        const request = target && !STATIC_FILE.test(target) ? { method: "GET", target } : undefined;
        add(withRequest({ element: "link", event: "click", handler: id, line: ln, ...caption }, request));
      }
    }
  }
  return out;
}

/** Attribute names a selector can use: not the id/class (spelled `#`/`.`), styling, events or accessibility text. */
const SELECTOR_SKIP = /^(?:id|class|style|type|href|src|alt|title|value|placeholder|tabindex|role|for|disabled|checked|selected|on\w+|aria-.*|data-bs-.*)$/i;

/** `button#save.btn[data-delete][name=club]` — tag, id, classes and the other attributes (a plain value kept); null when only the tag is known. */
export function selectorOf(tag: string, attrs: string): string | null {
  let id = "";
  const classes: string[] = [];
  const names: string[] = [];
  for (const m of attrs.matchAll(/([^\s=/>"']+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g)) {
    const name = m[1]!.toLowerCase();
    const value = (m[2] ?? m[3] ?? m[4] ?? "").trim();
    if (name === "id") id = /^[\w-]+$/.test(value) ? value : "";
    else if (name === "class") classes.push(...value.split(/\s+/).filter((c) => /^[\w-]+$/.test(c)));
    else if (!SELECTOR_SKIP.test(name) && /^[a-z][\w:-]*$/.test(name)) names.push(/^[\w-]{1,40}$/.test(value) ? `${name}=${value}` : name);
  }
  if (!id && classes.length === 0 && names.length === 0) return null;
  return `${tag}${id ? `#${id}` : ""}${classes.map((c) => `.${c}`).join("")}${names.map((n) => `[${n}]`).join("")}`;
}

// ─── Spec ───────────────────────────────────────────────────────────────────

export const htmlSpec: RegexLangSpec = {
  language: "html",
  extensions: [".html", ".htm"],
  blockStyle: "brace",
  lineCommentPrefixes: ["<!--"],

  // Behaviour lives in the `<script src>` JS files (parsed by the JS plugin).
  functionPatterns: [],
  classPatterns: [],

  importPatterns: [
    {
      // LOCAL `<script src="./x.js">` only — CDN/absolute URLs aren't project
      // files. Ties the page to its JS modules in the import/component graph.
      // TS/JSX sources too: a Vite page loads `<script type="module"
      // src="/src/main.ts">` straight from source.
      pattern: /<script\b[^>]*\bsrc\s*=\s*["'](?!https?:|\/\/)([^"']+\.[cm]?[jt]sx?)["']/i,
      getSource: (m) => m[1]!,
      getSpecifiers: () => [],
    },
  ],

  extractRoutes: (lines, _classes, filePath) => extractHtmlRoutes(lines, filePath),
  // Requests the page's inline scripts make (`fetch("/signup/code", { method: "POST" })`).
  extractDataSources: (lines) => inlineScriptRequests(lines),
  // A server-rendered page's forms and links request the app's routes (`materializeElementRequests`, in meta.ts).
  extractInteractiveElements: (lines) => extractHtmlInteractiveElements(lines, { requests: true }),
};
