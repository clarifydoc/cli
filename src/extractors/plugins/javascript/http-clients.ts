import type { Node, Tree } from "web-tree-sitter";
import type { HttpClientRegistration } from "../../../types/analysis.js";
import { jsBaseRefOf } from "./service-config.js";

/**
 * HTTP client instances a file creates with a base URL —
 *   const apiClient = axios.create({ baseURL: import.meta.env.VITE_API_URL || "/api" })
 *   const api = ky.create({ prefixUrl: "https://host/v1" })   (also `.extend`)
 *   export const client = createClient(createConfig({ baseUrl: '/api/v2' }))   (hey-api, openapi-fetch)
 * → `{ apiClient: "/api", api: "/v1", client: "/api/v2" }` (`FileAnalysis.httpClientBases`).
 *
 * Only what the source states: a string literal, or the literal fallback of
 * `env || "…"` / `env ?? "…"` (the dev default the app runs with when the
 * variable is unset). A base built any other way is unknown and recorded
 * nothing — guessing it would move every call through the client.
 */
const CLIENT_FACTORY_RE = /\b(?:(?:axios|ky|got)\.(?:create|extend)|createClient)\s*\(/;
const BASE_KEYS = new Set(["baseURL", "baseUrl", "prefixUrl", "prefixURL"]);

/** The config object a client factory call is given: `axios.create({…})`, `createClient(createConfig({…}))`. */
function clientConfig(value: Node): Node | null {
  const fn = value.childForFieldName("function")?.text.replace(/\s+/g, "") ?? "";
  if (!/^(?:(?:axios|ky|got)\.(?:create|extend)|createClient)$/.test(fn)) return null;
  let config = value.childForFieldName("arguments")?.namedChildren[0];
  // hey-api: `createClient(createConfig<ClientOptions>({ baseUrl }))`.
  if (config?.type === "call_expression" && /^createConfig\b/.test(config.childForFieldName("function")?.text ?? "")) {
    config = config.childForFieldName("arguments")?.namedChildren[0];
  }
  return config?.type === "object" ? config : null;
}

export function extractHttpClientBases(tree: Tree, sourceText: string): Record<string, string> {
  if (!CLIENT_FACTORY_RE.test(sourceText)) return {};
  const out: Record<string, string> = {};
  for (const decl of tree.rootNode.descendantsOfType("variable_declarator")) {
    const name = decl.childForFieldName("name");
    const value = decl.childForFieldName("value");
    if (name?.type !== "identifier" || value?.type !== "call_expression") continue;
    const config = clientConfig(value);
    if (!config) continue;
    for (const pair of config.namedChildren) {
      if (pair.type !== "pair") continue;
      const key = pair.childForFieldName("key")?.text.replace(/^['"]|['"]$/g, "");
      if (!key || !BASE_KEYS.has(key)) continue;
      const base = basePath(pair.childForFieldName("value"));
      if (base !== null) out[name.text] = base;
    }
  }
  return out;
}

/**
 * The same client instances, as registrations that keep what `basePath`
 * drops: the host of a literal base (`baseURL: "http://orders:8080/api"`) and
 * a base read from the environment (`baseURL: process.env.ORDERS_URL`). The
 * call-origin pass follows a call through its client to these, to find the
 * service it reaches. A base that is only a path names no service.
 */
/**
 * A module an OpenAPI / jsight generator writes a client class into: a
 * `generated` folder, or a published `*-typescript-axios` / `-fetch` package.
 */
/** The header OpenAPI Generator writes into every file it generates. */
const GENERATOR_HEADER = /auto generated by OpenAPI Generator|generated by Openapi Generator/i;

const GENERATED_CLIENT_SOURCE = /(?:^|\/)(?:generated|gen|__generated__)(?:\/|$)|typescript-(?:axios|fetch|angular)|openapi-client|-api-client$/i;

/**
 * Generated API client classes this file constructs (`new PersonsApi(config)`,
 * `new AbsenceWidgetInfoApi(url)`) from a generated module the tree usually
 * does not hold (git-ignored build output, an npm package): each is a client
 * proxy of the API class it is named for, so every call on an instance is a
 * request to the operation of that name — joined by `contract` to the route
 * the spec declares, here or in another repository.
 */
function generatedClientProxies(tree: Tree, sourceText: string): HttpClientRegistration[] {
  // The generator's own output, kept in the tree: its header says so, and each API class it declares is one.
  if (GENERATOR_HEADER.test(sourceText.slice(0, 2000))) {
    return [...sourceText.matchAll(/^export\s+class\s+([A-Z]\w*Api)\s+extends\s+BaseAPI\b/gm)].map((m) => ({
      client: m[1]!,
      scope: "project" as const,
      proxyOf: m[1]!,
      line: sourceText.slice(0, m.index).split("\n").length,
    }));
  }
  if (!/\bnew\s+[A-Z]\w*Api\s*\(/.test(sourceText)) return [];
  const generated = new Set<string>();
  for (const imp of tree.rootNode.descendantsOfType("import_statement")) {
    const source = imp?.childForFieldName("source")?.text.replace(/^['"]|['"]$/g, "") ?? "";
    if (!GENERATED_CLIENT_SOURCE.test(source)) continue;
    for (const spec of imp!.descendantsOfType("import_specifier")) {
      const local = (spec?.childForFieldName("alias") ?? spec?.childForFieldName("name"))?.text;
      if (local && /^[A-Z]\w*Api$/.test(local)) generated.add(local);
    }
  }
  const out: HttpClientRegistration[] = [];
  const seen = new Set<string>();
  for (const ne of tree.rootNode.descendantsOfType("new_expression")) {
    const cls = ne?.childForFieldName("constructor")?.text;
    if (!cls || !generated.has(cls) || seen.has(cls)) continue;
    seen.add(cls);
    out.push({ client: cls, scope: "project", proxyOf: cls, line: ne!.startPosition.row + 1 });
  }
  return out;
}

export function extractHttpClientRegistrations(tree: Tree, sourceText: string): HttpClientRegistration[] {
  const proxies = generatedClientProxies(tree, sourceText);
  if (!CLIENT_FACTORY_RE.test(sourceText)) return proxies;
  const out: HttpClientRegistration[] = [...proxies];
  for (const decl of tree.rootNode.descendantsOfType("variable_declarator")) {
    const name = decl.childForFieldName("name");
    const value = decl.childForFieldName("value");
    if (name?.type !== "identifier" || value?.type !== "call_expression") continue;
    const config = clientConfig(value);
    if (!config) continue;
    for (const pair of config.namedChildren) {
      if (pair.type !== "pair") continue;
      const key = pair.childForFieldName("key")?.text.replace(/^['"]|['"]$/g, "");
      if (!key || !BASE_KEYS.has(key)) continue;
      const base = jsBaseRefOf(pair.childForFieldName("value")?.text ?? "");
      if (base) out.push({ client: name.text, scope: "file", base, line: pair.startPosition.row + 1 });
    }
  }
  return out;
}

/** The path part of a stated base URL, without a trailing slash; null when not stated. */
function basePath(node: Node | null | undefined): string | null {
  if (!node) return null;
  if (node.type === "parenthesized_expression") return basePath(node.namedChildren[0]);
  if (node.type === "binary_expression") {
    const op = node.childForFieldName("operator")?.text;
    if (op === "||" || op === "??") return basePath(node.childForFieldName("right"));
    return null;
  }
  let text: string | null = null;
  if (node.type === "string") text = node.text.slice(1, -1);
  else if (node.type === "template_string" && !node.namedChildren.some((c) => c.type === "template_substitution")) {
    text = node.text.slice(1, -1);
  }
  if (text === null) return null;
  const path = /^[a-z][a-z0-9+.-]*:\/\/[^/]*(.*)$/i.exec(text)?.[1] ?? text;
  if (path !== "" && !path.startsWith("/")) return null;
  return path.replace(/\/+$/, "");
}
