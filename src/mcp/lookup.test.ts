import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { mkdtemp, mkdir, rm, writeFile } from "fs/promises";
import { tmpdir } from "os";
import { join } from "path";
import { analyze } from "../core/analyzer.js";
import { buildMcpServer } from "./server.js";
import { symbolSpellings } from "./tools/context.js";

/**
 * Four lookups that save an agent a round trip: a mistyped file path, a
 * generated namesake ranked below shipped code, a class's calls out of it,
 * and `Type::method` for `Type.method`.
 */
describe("MCP lookup leftovers", () => {
  let dir: string;
  let call: (tool: string, args: Record<string, unknown>) => Promise<string>;
  beforeAll(async () => {
    dir = await mkdtemp(join(tmpdir(), "clarifydoc-lookup-"));
    const file = async (path: string, text: string) => {
      await mkdir(join(dir, path, ".."), { recursive: true });
      await writeFile(join(dir, path), text);
    };
    await file("package.json", '{"name":"league","version":"1.0.0"}');
    await file(
      "src/services/ClubService.ts",
      'import { audit } from "../util/audit";\nimport { helper } from "./helper";\nexport class ClubService {\n  signPlayer(name: string): void { audit(name); this.log(name); }\n  release(name: string): void { helper(name); audit(name); }\n  private log(n: string): void {}\n}\n',
    );
    await file("src/services/helper.ts", "export function helper(n: string): void {}\n");
    await file("src/services/ClubService.py", "def x():\n    pass\n");
    await file("src/util/audit.ts", "export function audit(n: string): void {}\n");
    await file("src/util/buildClub.ts", "export function buildClub(): number { return 1; }\n");
    await file("generated/buildClub.ts", "// Code generated by clubgen. DO NOT EDIT.\nexport function buildClub(): number { return 2; }\n");
    await file("src/garage.ts", "export class Garage {\n  park(car: string): void {}\n}\nexport function enter(g: Garage): void { g.park('x'); }\n");
    await analyze({ projectRoot: dir, outputDir: join(dir, ".clarifydoc"), lsp: false, gitHistory: false });
    const { server } = buildMcpServer({ projectRoot: dir, analysisDir: join(dir, ".clarifydoc"), allowAnalyze: false, allowColdStart: false });
    call = async (name, args) => {
      const res = await server.handleMessage({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name, arguments: args } });
      const r = res?.result as { content: Array<{ text: string }> } | undefined;
      return r ? r.content[0]!.text : JSON.stringify(res);
    };
  }, 60_000);
  afterAll(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it("a mistyped file path gets did-you-mean suggestions of the same extension", async () => {
    const text = await call("clarifydoc_file", { path: "src/services/ClubServise.ts" });
    expect(text).toContain("No analyzed file matches");
    expect(text).toContain("Did you mean");
    expect(text).toContain("src/services/ClubService.ts");
    expect(text).not.toContain("ClubService.py");
  });

  it("no suggestion is made for a path nothing is near", async () => {
    const text = await call("clarifydoc_file", { path: "src/zzzzzzzz.ts" });
    expect(text).toContain("No analyzed file matches");
    expect(text).not.toContain("Did you mean");
  });

  it("search ranks a generated definition below the shipped one", async () => {
    const text = await call("clarifydoc_search", { query: "buildClub", kinds: ["symbol"] });
    const rows = text.split("\n").filter((l) => l.startsWith("- "));
    expect(rows[0]).toContain("src/util/buildClub.ts");
    expect(rows[1]).toContain("generated/buildClub.ts");
  });

  it("explain on a class lists what its methods call outside it, by target file", async () => {
    const text = await call("clarifydoc_explain", { subject: "ClubService" });
    expect(text).toContain("## Calls out of the class");
    const block = text.split("## Calls out of the class")[1]!.split("\n## ")[0]!;
    expect(block).toContain("src/util/audit.ts");
    expect(block).toContain("audit");
    expect(block).toContain("src/services/helper.ts");
    expect(block).not.toContain("log");
  });

  it("extract finds Garage.park for Garage::park", async () => {
    const text = await call("clarifydoc_extract", { symbol: "Garage::park", depth: 0 });
    expect(text).toMatch(/Garage\.park\(\)/);
  });

  it("trace, explain and rename_plan read Garage::park the same way", async () => {
    expect(await call("clarifydoc_trace", { symbol: "Garage::park", direction: "callers" })).toContain("enter");
    expect(await call("clarifydoc_explain", { subject: "Garage::park" })).not.toContain("Nothing in the analysis is named");
    expect(await call("clarifydoc_rename_plan", { symbol: "Garage::park", to: "stow" })).not.toContain("No function, method or class named");
  });

  it("trace reads `to` as Garage::park too", async () => {
    const text = await call("clarifydoc_trace", { symbol: "enter", to: "Garage::park" });
    expect(text).toContain("park");
    expect(text).not.toMatch(/^No /);
  });

  it("symbolSpellings: as written first, then `::` and `->` read as `.`", () => {
    expect(symbolSpellings("Garage::park")).toEqual(["Garage::park", "Garage.park"]);
    expect(symbolSpellings("Garage->park")).toEqual(["Garage->park", "Garage.park"]);
    expect(symbolSpellings("Garage.park")).toEqual(["Garage.park"]);
  });
});
