/* Same shapes as decls.c with the roles swapped: here Car and Club are plain variables, not types. */
int Car, Club, garage;

int shapes2(int a, int b) {
  int total = 0;
  Car * Club;
  Car(total);
  total = (Car)garage + (Club) - a;
  total = (garage)(a);
  if (a < b && b > a) { total = 1; }
  return total;
}
