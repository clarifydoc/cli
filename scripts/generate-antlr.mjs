#!/usr/bin/env node
/**
 * Regenerates the antlr4ng parsers in src/parsers/antlr/<lang>/ from the grammars in grammars/antlr/<lang>/.
 * The generated TypeScript is committed, so a build never needs this; run it after changing a grammar or
 * upgrading antlr-ng. Only the lexer and parser are kept (no listener: the readers walk the tree themselves,
 * and the .interp/.tokens files are the tool's own). Each starts
 * with its grammar's licence block as a legal comment (`/*!`), which the bundle keeps in dist/.
 *
 *   node scripts/generate-antlr.mjs [lang…]
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const grammarRoot = join(root, "grammars", "antlr");
const langs = process.argv.length > 2
  ? process.argv.slice(2)
  : readdirSync(grammarRoot, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
const tool = join(root, "node_modules", ".bin", "antlr-ng");

for (const lang of langs) {
  const dir = join(grammarRoot, lang);
  // Lexer grammars first: a parser grammar reads its token vocabulary.
  const grammars = readdirSync(dir).filter((f) => f.endsWith(".g4")).sort((a, b) => Number(b.includes("Lexer")) - Number(a.includes("Lexer")));
  const out = mkdtempSync(join(tmpdir(), `antlr-${lang}-`));
  execFileSync(tool, ["-Dlanguage=TypeScript", "--generate-listener", "false", "-o", out, "--lib", dir, ...grammars.map((g) => join(dir, g))], { stdio: "inherit" });
  const target = join(root, "src", "parsers", "antlr", lang);
  for (const file of readdirSync(out).filter((f) => f.endsWith(".ts"))) {
    // GoParserListener.ts comes from GoParser.g4, GoLexer.ts from GoLexer.g4.
    const grammar = grammars.find((g) => file.startsWith(g.replace(/\.g4$/, ""))) ?? grammars.at(-1);
    // A lexer grammar may carry no licence block of its own; its parser grammar's covers it.
    const licenceOf = (g) => /^\s*\/\*([\s\S]*?)\*\//.exec(readFileSync(join(dir, g), "utf8"))?.[1];
    const licence = licenceOf(grammar) ?? grammars.map(licenceOf).find(Boolean) ?? "";
    const header = `/*! Generated by antlr-ng from grammars/antlr/${lang}/${grammar}, whose licence follows.\n${licence.trimEnd()}\n*/\n`;
    writeFileSync(join(target, file), header + readFileSync(join(out, file), "utf8"));
    console.log(`${lang}: ${file}`);
  }
  rmSync(out, { recursive: true, force: true });
}
